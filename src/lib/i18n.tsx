export type Copy = (typeof dict)["en"];

const Ctx = createContext<{ locale: Locale; t: Copy; toggle: () => void; setLocale: (locale: Locale) => void } | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>("fa");
  useEffect(() => {
    const saved = window.localStorage.getItem("sepehr-locale");
    if (saved === "en" || saved === "fa") setLocale(saved);
  }, []);
  useEffect(() => {
    document.documentElement.lang = locale === "fa" ? "fa" : "en";
    document.documentElement.dir = locale === "fa" ? "rtl" : "ltr";
    window.localStorage.setItem("sepehr-locale", locale);
  }, [locale]);
  const value = useMemo(
    () => ({
      locale,
      t: dict[locale],
      toggle: () => setLocale((current) => (current === "fa" ? "en" : "fa")),
      setLocale,
    }),
    [locale],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("locale");
  return ctx;
}

export function hotelMessage(error: unknown, t: Copy): string {
  const raw = error instanceof Error ? error.message : String(error ?? "");
  const code = raw.startsWith("HOTEL:") ? raw.slice(6) : /unauthorized/i.test(raw) ? "unauthorized" : "unknown";
  return t.errors[code] ?? t.errors.unknown;
}

export function statusLabel(code: string, t: Copy): string {
  return t.statuses[code] ?? code;
}

export function deptLabel(code: string, t: Copy): string {
  return t.depts[code] ?? code;
}
